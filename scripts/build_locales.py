"""Build the four-language dictionary and the English-first HTML fallback.

Run from the repository root after editing localization_rows.json.
The source list preserves the original Portuguese strings by stable index.
Requires BeautifulSoup4. Does not use a translation service at runtime.
"""
import json
from pathlib import Path
from bs4 import BeautifulSoup, Doctype, Comment

ROOT = Path(__file__).resolve().parents[1]
original = json.loads((ROOT/'scripts/localization_source.json').read_text(encoding='utf-8'))
rows = json.loads((ROOT/'scripts/localization_rows.json').read_text(encoding='utf-8'))
locales = {language: {} for language in ('en', 'es', 'pt', 'zh')}
for index, en, es, zh in rows:
    key = f't{index:03}'
    assert key not in locales['en'], f'Duplicate translation: {key}'
    for language, value in [('en', en), ('es', es), ('pt', original[index]), ('zh', zh)]:
        assert value.strip()
        locales[language][key] = value

ui = {
 'languageLabel': ['Language', 'Idioma', 'Idioma', '语言'],
 'emailCopied': ['Email copied!', '¡Correo copiado!', 'E-mail copiado!', '邮箱地址已复制！'],
 'emailCopiedLabel': ['Email copied. Copy again', 'Correo copiado. Copiar de nuevo', 'E-mail copiado. Copiar novamente', '邮箱地址已复制。再次复制'],
 'emailCopyError': ['Select the address to copy it, or click it to send an email.', 'Selecciona la dirección para copiarla o haz clic para enviar un correo.', 'Selecione o endereço para copiar ou clique nele para enviar um e-mail.', '请选择邮箱地址进行复制，或点击地址发送电子邮件。'],
}
for key, values in ui.items():
    for language, value in zip(('en', 'es', 'pt', 'zh'), values): locales[language][key] = value

# Several strings can share a translation only when they agree in all locales.
seen = {}
for key, value in locales['en'].items():
    if value in seen:
        assert all(locales[lang][seen[value]] == locales[lang][key] for lang in locales), value
    seen[value] = key

(ROOT/'i18n.js').write_text('// Generated by scripts/build_locales.py. Edit the localization source files.\nwindow.PORTFOLIO_TRANSLATIONS = '+json.dumps(locales,ensure_ascii=False,indent=2)+';\n',encoding='utf-8',newline='\n')

soup=BeautifulSoup((ROOT/'index.html').read_text(encoding='utf-8'),'html.parser')
source_keys = {original[index]: f't{index:03}' for index, en, es, zh in rows}
source_keys.update({en: f't{index:03}' for index, en, es, zh in rows})
for node in list(soup.find_all(string=True)):
    if isinstance(node,(Doctype,Comment)) or node.parent.name in ('script','style'): continue
    if node.find_parent(attrs={'data-i18n-skip':True}): continue
    value=str(node)
    marker=node.previous_sibling
    marked=isinstance(marker,Comment) and str(marker).startswith('i18n:')
    key=str(marker)[5:] if marked else source_keys.get(value.strip())
    if key in locales['en']:
        prefix=value[:len(value)-len(value.lstrip())]
        suffix=value[len(value.rstrip()):]
        if node.parent.name=='title':
            node.parent['data-i18n']=key
        elif not marked:
            node.insert_before(Comment('i18n:'+key))
        node.replace_with(prefix+locales['en'][key]+suffix)
for element in soup.find_all(True):
    for attribute in ('aria-label','alt','content'):
        value=element.get(attribute)
        key=element.get('data-i18n-'+attribute) or source_keys.get(value)
        if key in locales['en']:
            element[attribute]=locales['en'][key]
            element['data-i18n-'+attribute]=key
soup.html['lang']='en'
if not soup.select_one('script[src^="i18n.js"]'):
    script=soup.new_tag('script',src='i18n.js?v=20261105-languages',defer='')
    soup.select_one('script[src^="script.js"]').insert_before(script)
soup.select_one('script[src^="script.js"]')['src']='script.js?v=20261105-languages'
soup.select_one('link[rel="stylesheet"]')['href']='styles.css?v=20261105-languages'
if not soup.select_one('meta[property="og:locale"]'):
    soup.head.append(soup.new_tag('meta',attrs={'property':'og:locale','content':'en_US'}))
if not soup.select_one('#language-select'):
    control=BeautifulSoup('''<label class="language-control"><svg class="icon" aria-hidden="true" viewBox="0 0 24 24"><circle cx="12" cy="12" r="9"/><ellipse cx="12" cy="12" rx="4" ry="9"/><path d="M3 12h18"/></svg><span class="sr-only">Language</span><select id="language-select" aria-label="Language" data-i18n-skip><option value="en" lang="en" selected>English</option><option value="es" lang="es">Español</option><option value="pt" lang="pt-BR">Português</option><option value="zh" lang="zh-Hans">简体中文</option></select></label>''','html.parser')
    soup.select_one('.nav-links').append(control.label)
soup.select_one('.evidence-quote blockquote')['lang']='en'
soup.select_one('.evidence-quote blockquote')['data-i18n-skip']=''
(ROOT/'index.html').write_text(str(soup).rstrip()+'\n',encoding='utf-8',newline='\n')
print(f'Built {len(rows)} content translations plus {len(ui)} interface strings in four languages.')
